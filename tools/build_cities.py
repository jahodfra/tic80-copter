#!/usr/bin/env python3
"""Generate cart/src/20_cities.lua from Natural Earth populated places (public domain).

Keeps capitals, big cities (population >= 1M) and well-known places (scalerank <= 3),
drops places closer than ~60 km to a more important one, and writes them as one compact
string: "name;country index;lat;lon;fame" per line (fame 0 = world famous .. 3 = obscure).

Usage: python3 tools/build_cities.py raw/naturalearth/ne_10m_populated_places_simple.dbf
"""
import math
import struct
import sys

SHORT = {
    "United States of America": "USA",
    "United Kingdom": "UK",
    "Democratic Republic of the Congo": "DR Congo",
    "Republic of the Congo": "Congo",
    "Central African Republic": "C. African Rep.",
    "Bosnia and Herzegovina": "Bosnia",
    "United Arab Emirates": "UAE",
    "Dominican Republic": "Dominican Rep.",
    "Trinidad and Tobago": "Trinidad",
    "Papua New Guinea": "Papua N. Guinea",
    "Saint Vincent and the Grenadines": "St Vincent",
    "Antigua and Barbuda": "Antigua",
    "Sao Tome and Principe": "Sao Tome",
    "Federated States of Micronesia": "Micronesia",
    "Saint Kitts and Nevis": "St Kitts",
    "Republic of Serbia": "Serbia",
    "United Republic of Tanzania": "Tanzania",
    "The Bahamas": "Bahamas",
    "Czechia": "Czech Republic",
}


def read_dbf(path):
    f = open(path, "rb").read()
    n, hl, rl = struct.unpack("<IHH", f[4:12])
    fields, p = [], 32
    while f[p] != 0x0D:
        fields.append((f[p:p + 11].split(b"\0")[0].decode(), f[p + 16]))
        p += 32
    for i in range(n):
        r = f[hl + i * rl + 1:hl + (i + 1) * rl]
        o, d = 0, {}
        for nm, ln in fields:
            d[nm] = r[o:o + ln].decode("utf-8", "replace").strip()
            o += ln
        yield d


def dist(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (a["lat"], a["lon"], b["lat"], b["lon"]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 6371 * 2 * math.asin(min(1, math.sqrt(h)))


def main():
    places = []
    for r in read_dbf(sys.argv[1]):
        if r["featurecla"] in ("Scientific station", "Meteorological Station", "Historic place"):
            continue
        pop = int(float(r["pop_max"] or 0))
        rank = int(r["scalerank"])
        cap = r["adm0cap"] in ("1", "1.0") or r["featurecla"] == "Admin-0 capital"
        if not (cap or pop >= 1_000_000 or rank <= 3):
            continue
        name = r["nameascii"] or r["name"]
        if not name.isascii():
            continue
        fame = 0 if rank <= 1 else 1 if rank <= 2 else 2 if (rank <= 3 or pop >= 3_000_000) else 3
        if cap and fame > 1:
            fame -= 1
        places.append(dict(name=name, country=SHORT.get(r["adm0name"], r["adm0name"]),
                           lat=float(r["latitude"]), lon=float(r["longitude"]),
                           fame=fame, cap=cap, pop=pop))
    places.sort(key=lambda p: (p["fame"], not p["cap"], -p["pop"]))
    kept = []
    for p in places:
        if all(dist(p, k) > 60 for k in kept):
            kept.append(p)
    countries = sorted({p["country"] for p in kept})
    ci = {c: i + 1 for i, c in enumerate(countries)}
    lines = []
    for p in kept:
        kind = 1 if p["cap"] else (2 if p["pop"] >= 5_000_000 else 0)
        lines.append(f'{p["name"]};{ci[p["country"]]};{p["lat"]:.2f};{p["lon"]:.2f};{p["fame"]};{kind}')
    out = ["-" * 40 + " cities (generated by tools/build_cities.py from Natural Earth)",
           "COUNTRIES={" + ",".join(f'"{c}"' for c in countries) + "}",
           "CITY_DATA=[[",
           *lines,
           "]]", ""]
    path = "cart/src/20_cities.lua"
    open(path, "w").write("\n".join(out))
    print(f"{path}: {len(kept)} cities in {len(countries)} countries, fame counts",
          [sum(p['fame'] == f for p in kept) for f in range(4)])


if __name__ == "__main__":
    main()
